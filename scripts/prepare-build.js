import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import esbuild from 'esbuild';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');

const distDir = path.join(rootDir, 'dist');
const buildDir = path.join(rootDir, 'build');

async function run() {
  console.log('--------------------------------------------------');
  console.log('🔧 Running SAI Ethio • SeeraAI Build Artifacts Preparation');
  console.log('--------------------------------------------------');

  // 1. Verify dist exists and has index.html
  const distIndex = path.join(distDir, 'index.html');
  if (!fs.existsSync(distIndex)) {
    console.error('❌ ERROR: dist/index.html was not generated by Vite build!');
    process.exit(1);
  }
  const indexStat = fs.statSync(distIndex);
  if (indexStat.size === 0) {
    console.error('❌ ERROR: dist/index.html is empty (0 bytes)!');
    process.exit(1);
  }
  console.log(`✅ Verified dist/index.html (${indexStat.size} bytes)`);

  // 2. Bundle server-app.ts into dist/server.js
  console.log('⚡ Bundling server-app.ts with esbuild for production Node container...');
  try {
    await esbuild.build({
      entryPoints: [path.join(rootDir, 'server-app.ts')],
      bundle: true,
      platform: 'node',
      format: 'esm',
      packages: 'external',
      outfile: path.join(distDir, 'server.js'),
      minify: false,
      sourcemap: false,
    });
    console.log('✅ Generated dist/server.js production server bundle.');
  } catch (err) {
    console.error('❌ Failed to bundle server-app.ts:', err);
    process.exit(1);
  }

  // 3. (REMOVED) Mirror dist to build for deployment compatibility
  // In the current environment, we only need dist/ to save space and avoid 250MB limits.
  console.log('ℹ️ Skipping mirroring dist/ to build/ to optimize workspace size.');

  // 4. Calculate statistics and write build manifest
  let totalFiles = 0;
  let totalBytes = 0;

  function scanDir(dir) {
    const entries = fs.readdirSync(dir, { withFileTypes: true });
    for (const entry of entries) {
      const fullPath = path.join(dir, entry.name);
      if (entry.isDirectory()) {
        scanDir(fullPath);
      } else if (entry.isFile()) {
        totalFiles++;
        totalBytes += fs.statSync(fullPath).size;
      }
    }
  }

  scanDir(distDir);
  const totalMb = (totalBytes / (1024 * 1024)).toFixed(2);

  const manifest = {
    appName: 'SAI Ethio • SeeraAI Legal Platform',
    version: '4.1.0',
    buildTime: new Date().toISOString(),
    totalFiles,
    totalBytes,
    totalMb: `${totalMb} MB`,
    entrypoints: {
      spa: 'index.html',
      server: 'server.js',
    },
  };

  fs.writeFileSync(path.join(distDir, 'build-manifest.json'), JSON.stringify(manifest, null, 2));

  console.log('==================================================');
  console.log('🎉 BUILD ARTIFACTS VERIFICATION SUCCESS');
  console.log(`📦 dist/: ${totalFiles} files, ${totalMb} MB`);
  console.log(`📦 build/: ${totalFiles} files mirrored`);
  console.log(`🚀 Node Server: dist/server.js ready`);
  console.log('==================================================');
}

run().catch((err) => {
  console.error('Fatal error during build preparation:', err);
  process.exit(1);
});
